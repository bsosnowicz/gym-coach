-- Injuries and pain reported in conversation (src/coach/injury-store.js).
-- Same shape as yoga-startup's user_injuries: one row per user and body part;
-- body_part is the closed list BODY_PARTS from src/coach/exercises.js.
-- Only the server writes here, with the service_role key; no access for anon
-- and authenticated until the app has accounts.

create table if not exists public.user_injuries (
  id bigint generated by default as identity primary key,
  user_id text not null,
  body_part text not null check (body_part in (
    'shoulder_left', 'shoulder_right', 'elbow_left', 'elbow_right',
    'knee_left', 'knee_right', 'wrist_left', 'wrist_right',
    'ankle_left', 'ankle_right', 'hip_left', 'hip_right',
    'lower_back', 'upper_back', 'neck',
    'calf_left', 'calf_right', 'hamstring_left', 'hamstring_right',
    'ribs', 'groin', 'other'
  )),
  status text not null default 'active' check (status in ('active', 'resolved')),
  severity text check (severity in ('low', 'medium', 'high')),
  note text,
  source_session_id text,
  reported_at timestamptz not null default now(),
  resolved_at timestamptz,
  unique (user_id, body_part)
);

create index if not exists user_injuries_user_status_idx
  on public.user_injuries (user_id, status, reported_at desc);

alter table public.user_injuries enable row level security;
revoke all on public.user_injuries from anon, authenticated;
grant all on public.user_injuries to service_role;
grant usage, select on sequence public.user_injuries_id_seq to service_role;
